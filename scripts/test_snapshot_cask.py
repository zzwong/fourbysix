"""Synthetic checker tests; no Go build, network, Ruby evaluation or host access."""
import importlib.util
import pathlib
import unittest

spec = importlib.util.spec_from_file_location("checker", pathlib.Path(__file__).with_name("check-snapshot-cask.py"))
checker = importlib.util.module_from_spec(spec)
spec.loader.exec_module(checker)

def package_block(platform, goos):
    arches = []
    for ruby_arch, goarch in (("intel", "amd64"), ("arm", "arm64")):
        arches.append(
            f'    on_{ruby_arch} do\n'
            f'      sha256 "{"a" * 64}"\n'
            f'      url "https://github.com/zzwong/fourbysix/releases/download/v0.1.3-SNAPSHOT-test/fourbysix_0.1.3-SNAPSHOT-test_{goos}_{goarch}.tar.gz"\n'
            '    end\n'
        )
    return f"  on_{platform} do\n" + "".join(arches) + "  end\n"


MAC = package_block("macos", "darwin")
LINUX = package_block("linux", "linux")
VALID = (
    '# This file was generated by GoReleaser. DO NOT EDIT.\n'
    'cask "fourbysix" do\n'
    '  on_macos do\n    depends_on macos: :ventura\n  end\n'
    '  version "0.1.3-SNAPSHOT-test"\n'
    + MAC + LINUX +
    '  binary "fourbysix"\nend\n'
)


class Contract(unittest.TestCase):
    def test_expected(self):
        checker.check(VALID)

    def test_rejected_mutations(self):
        mutations = {
            "missing_guard": VALID.replace("    depends_on macos: :ventura\n", ""),
            "wrong_minimum": VALID.replace(":ventura", ":monterey"),
            "linux_guard": VALID.replace("  on_macos do\n    depends_on", "  on_linux do\n    depends_on"),
            "global_guard": VALID.replace("  on_macos do\n    depends_on macos: :ventura\n  end", "  depends_on macos: :ventura"),
            "duplicate_guard": VALID.replace('  version', '  on_macos do\n    depends_on macos: :ventura\n  end\n  version'),
            "global_macos": VALID.replace('  version', '  depends_on :macos\n  version'),
            "missing_linux": VALID.replace("  on_linux do", "  on_windows do"),
            "missing_binary": VALID.replace('  binary "fourbysix"', ""),
            "wrong_binary": VALID.replace('  binary "fourbysix"', '  binary "other"'),
            "wrong_name": VALID.replace('cask "fourbysix"', 'cask "other"'),
            "unresolved": VALID.replace("0.1.3-SNAPSHOT-test", "{{ .Version }}"),
            "comment_guard": VALID.replace("    depends_on", "    # depends_on"),
            "nested_guard": VALID.replace("  on_macos do\n    depends_on macos: :ventura\n  end", "    on_macos do\n      depends_on macos: :ventura\n    end"),
        }
        for name, text in mutations.items():
            with self.subTest(name=name):
                with self.assertRaises(ValueError):
                    checker.check(text)

    def test_package_mutations(self):
        mutations = {
            "guard_only_macos": VALID.replace(MAC, ""),
            "empty_linux": VALID.replace(LINUX, "  on_linux do\n  end\n"),
            "empty_macos": VALID.replace(MAC, "  on_macos do\n  end\n"),
            "linux_urls_in_macos": VALID.replace(MAC, MAC.replace("_darwin_", "_linux_")),
            "wrong_arch_url": VALID.replace("_linux_arm64.tar.gz", "_linux_amd64.tar.gz"),
            "missing_arm": VALID.replace('    on_arm do', '    on_other do'),
            "missing_checksum": VALID.replace(f'      sha256 "{"a" * 64}"\n', ""),
            "short_checksum": VALID.replace("a" * 64, "abcd"),
            "wrong_repo": VALID.replace("/zzwong/fourbysix/", "/other/fourbysix/"),
            "wrong_archive": VALID.replace(".tar.gz", ".zip"),
            "comment_url": VALID.replace('      url ', '      # url '),
            "duplicate_packages": VALID.replace(MAC, MAC + MAC),
            "empty_url": VALID.replace('https://github.com/zzwong/fourbysix/releases/download/v0.1.3-SNAPSHOT-test/fourbysix_0.1.3-SNAPSHOT-test_linux_arm64.tar.gz', ""),
        }
        for name, text in mutations.items():
            with self.subTest(name=name):
                with self.assertRaises(ValueError):
                    checker.check(text)

    def test_pinned_generator_placeholders(self):
        # GoReleaser replaces the snapshot version in archive URLs with Ruby's
        # version interpolation, but leaves its Homebrew staged_path token.
        generated = VALID.replace(
            "fourbysix_0.1.3-SNAPSHOT-test_", "fourbysix_#{version}_"
        ).replace(
            '  binary "fourbysix"',
            '  binary "fourbysix"\n'
            '  postflight_steps do\n'
            '    on_macos do\n'
            '      run "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "{{staged_path}}/fourbysix"]\n'
            '    end\n'
            '  end'
        )
        checker.check(generated)
        checker.check(generated.replace("/download/v0.1.3-SNAPSHOT-test/", "/download/v#{version}/"))
        mutations = {
            "interpolation_in_version": generated.replace('version "0.1.3-SNAPSHOT-test"', 'version "#{version}"'),
            "interpolation_in_description": generated.replace('  binary "fourbysix"', '  desc "#{version}"\n  binary "fourbysix"'),
            "unknown_tag_interpolation": generated.replace("/download/v0.1.3-SNAPSHOT-test/", "/download/v#{other}/"),
            "suffix_tag_interpolation": generated.replace("/download/v0.1.3-SNAPSHOT-test/", "/download/v#{version}-suffix/"),
            "wrong_homebrew_token": generated.replace("{{staged_path}}", "{{appdir}}"),
            "unexpanded_go_token": generated.replace("{{staged_path}}", "{{ .StagedPath }}"),
            "token_in_version": generated.replace('version "0.1.3-SNAPSHOT-test"', 'version "{{staged_path}}"'),
            "token_in_archive": generated.replace("#{version}", "{{staged_path}}"),
            "wrong_install_target": generated.replace("{{staged_path}}/fourbysix", "{{staged_path}}/other"),
            "wrong_url_interpolation": generated.replace("#{version}", "#{other}"),
            "missing_url_interpolation_brace": generated.replace("#{version}", "#{version"),
            "wrong_os_with_interpolation": generated.replace("_darwin_arm64", "_linux_arm64"),
        }
        for name, text in mutations.items():
            with self.subTest(name=name):
                with self.assertRaises(ValueError):
                    checker.check(text)


if __name__ == "__main__":
    unittest.main()
